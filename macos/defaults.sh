#!/usr/bin/env bash
# macOS defaults: capture current values into a replayable script, or apply it.
#
#   ./macos/defaults.sh capture   # snapshot current settings -> defaults.generated.sh
#   ./macos/defaults.sh apply     # replay defaults.generated.sh on a fresh machine
#
# Curated key list — extend KEYS as you find settings worth keeping.

set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
GENERATED="$HERE/defaults.generated.sh"

# "domain key"
KEYS=(
  "NSGlobalDomain KeyRepeat"
  "NSGlobalDomain InitialKeyRepeat"
  "NSGlobalDomain ApplePressAndHoldEnabled"
  "NSGlobalDomain AppleShowAllExtensions"
  "NSGlobalDomain AppleInterfaceStyle"
  "NSGlobalDomain NSAutomaticCapitalizationEnabled"
  "NSGlobalDomain NSAutomaticPeriodSubstitutionEnabled"
  "NSGlobalDomain NSAutomaticQuoteSubstitutionEnabled"
  "NSGlobalDomain NSAutomaticSpellingCorrectionEnabled"
  "com.apple.dock autohide"
  "com.apple.dock tilesize"
  "com.apple.dock show-recents"
  "com.apple.dock mineffect"
  "com.apple.finder ShowPathbar"
  "com.apple.finder ShowStatusBar"
  "com.apple.finder AppleShowAllFiles"
  "com.apple.finder FXPreferredViewStyle"
  "com.apple.finder FXDefaultSearchScope"
  "com.apple.screencapture location"
  "com.apple.screencapture type"
  "com.apple.screencapture disable-shadow"
  "com.apple.AppleMultitouchTrackpad Clicking"
  "com.apple.AppleMultitouchTrackpad TrackpadThreeFingerDrag"
)

capture() {
  {
    echo "#!/usr/bin/env bash"
    echo "# Generated by defaults.sh capture on $(hostname) at $(date '+%Y-%m-%d %H:%M')"
    echo "# Review before committing — then applied verbatim by bootstrap.sh."
    echo "set -euo pipefail"
    local entry domain key type value
    for entry in "${KEYS[@]}"; do
      domain="${entry% *}"; key="${entry#* }"
      if ! type="$(defaults read-type "$domain" "$key" 2>/dev/null)"; then
        continue  # key not set on this machine
      fi
      value="$(defaults read "$domain" "$key")"
      case "$type" in
        *boolean*)
          [[ "$value" == "1" ]] && value=true || value=false
          echo "defaults write $domain $key -bool $value" ;;
        *integer*) echo "defaults write $domain $key -int $value" ;;
        *float*)   echo "defaults write $domain $key -float $value" ;;
        *string*)  printf 'defaults write %s %s -string %q\n' "$domain" "$key" "$value" ;;
        *)         echo "# skipped $domain $key (unhandled $type)" ;;
      esac
    done
    echo 'killall Dock Finder SystemUIServer 2>/dev/null || true'
  } > "$GENERATED"
  chmod +x "$GENERATED"
  echo "captured -> ${GENERATED#"$HERE"/} ($(grep -c '^defaults write' "$GENERATED") settings)"
}

apply() {
  if [[ -x "$GENERATED" ]]; then
    "$GENERATED"
    echo "applied ${GENERATED#"$HERE"/}"
  else
    echo "no defaults.generated.sh yet — run: ./macos/defaults.sh capture" >&2
    exit 1
  fi
}

case "${1:-}" in
  capture) capture ;;
  apply)   apply ;;
  *) echo "usage: $0 {capture|apply}" >&2; exit 2 ;;
esac
